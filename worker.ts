。この言葉の背景には、封建的な身分制度や因習が人々の自主性を奪い、日本の近代国家としての発展を阻んでいるという問題意識があります。実際、福澤は旧来の門閥的秩序を「一身の独立を阻むもの、ひいては一国の独立のための障害」とみなし、これを取り除かねばならないと決意していました
